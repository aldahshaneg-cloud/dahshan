<?php

declare(strict_types=1);

namespace App\Wire;

use App\Support\Vocab;

/**
 * طبقة السلك للموقع العام — نقل حرفي لدوال التقنيع في api/routes/public_site.php.
 *
 * 🔒 **ده حد الخصوصية الوحيد على مسار مفتوح للدنيا كلها.** /api/track بيتنده
 * عليه من غير أي دخول، برقم شحنة بس. يعني أي حد معاه رقم شحنة (وهو مطبوع على
 * البوليصة وبيتبعت في SMS) بيوصل للرد ده. فالتقنيع مش تجميل — هو اللي بيمنع
 * إن حد يعدّ أرقام الشحنات ويطلّع دفتر عملاء الشركة كامل بأسماء وتليفونات.
 *
 * القواعد اللي ممنوع تتكسر هنا:
 *  • **مفيش أي مبلغ في الرد خالص** — لا سعر منطقة، ولا عهدة، ولا قيمة بضاعة،
 *    ولا مقدّم المحل. الاستعلام نفسه مابيسحبش الأعمدة دي أصلًا (دفاع في
 *    العمق: حتى لو حد زوّد مفتاح غلط بعدين، البيانات مش موجودة في الصف).
 *  • الأسماء (المستلم + الطيار) بتتقنّع بـ maskName.
 *  • التليفونات بتتقنّع بـ maskPhone.
 *  • اسم الفرع واسم المنطقة **مش** مقنّعين — دي بيانات تسويقية منشورة على
 *    الموقع أصلًا في /api/public/coverage.
 */
final class PublicWire
{
    /**
     * تقنيع اسم: أول حرف + نجوم — «أحمد» → «أ***».
     *
     * عدد النجوم = min(3, max(1, طول الاسم - 1)) — يعني **مابيفضحش طول الاسم**:
     * اسم من 4 حروف واسم من 20 حرف الاتنين بيطلعوا بـ 3 نجوم. لو الاسم حرف
     * واحد بيطلع نجمة واحدة (max(1,0) = 1) مش صفر، عشان مايبانش إنه حرف واحد.
     * الاسم الفاضي بيرجع «—» مش سلسلة فاضية — الواجهة بتعرض القيمة كما هي.
     */
    public static function maskName(?string $name): string
    {
        $name = trim((string) $name);
        if ($name === '') {
            return '—';
        }
        $first = mb_substr($name, 0, 1, 'UTF-8');

        return $first . str_repeat('*', min(3, max(1, mb_strlen($name, 'UTF-8') - 1)));
    }

    /**
     * تقنيع تليفون: آخر 4 أرقام بس — «01012345678» → «•••••••5678».
     *
     * ⚠️ التعليق في الكود القديم مكتوب «آخر 3 أرقام» بس الكود بيسيب **4**
     * (substr(-4)). الكود هو الحاكم — منقول بالحرف، والتعليق الغلط مش
     * بيتصلّح هنا لأن ده ترحيل صفر تغيير.
     *
     * الرموز غير الرقمية بتتشال الأول، فـ«010-1234-5678» بيتقنّع زي
     * «01012345678» بالظبط. أقل من 4 أرقام بيرجع «—» — رقم قصير كده مش
     * تليفون أصلًا، وتقنيعه كان هيسيبه مكشوف بالكامل.
     */
    public static function maskPhone(?string $p): string
    {
        $p = (string) preg_replace('/\D/', '', (string) $p);
        if ($p === '' || strlen($p) < 4) {
            return '—';
        }

        return str_repeat('•', max(0, strlen($p) - 4)) . substr($p, -4);
    }

    /**
     * طرد في رد التتبّع العام — نسخة مقنّعة ومقصوصة من كائن الطرد الكامل.
     *
     * قارن بـ OrderWire::delivery(): هناك 14 مفتاح فيهم zonePrice و orderPrice
     * و address و images. هنا **5 مفاتيح بس** ومفيش أي مبلغ ولا عنوان ولا صور.
     * الاختلاف ده مقصود — مش نسيان.
     */
    public static function trackParcel(array|object $row): array
    {
        $d = is_array($row) ? $row : (array) $row;

        return [
            'parcelNo'      => (int) $d['parcel_no'],
            'receiverName'  => self::maskName($d['receiver_name']),
            'receiverPhone' => self::maskPhone($d['receiver_phone']),
            // المنطقة جاية من COALESCE(NULLIF(d.zone_name,''), z.area_name) —
            // والفاضي بيبقى «—» مش سلسلة فاضية (فحص مرن `?:` زي الأصل).
            'zoneName'      => $d['zone_name'] ?: '—',
            'status'        => Vocab::parcelStatusToAr($d['status']),
        ];
    }
}
