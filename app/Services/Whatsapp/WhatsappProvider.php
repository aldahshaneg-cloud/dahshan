<?php

declare(strict_types=1);

namespace App\Services\Whatsapp;

/**
 * الواجهة اللي بتفصل «مين بيبعت» عن «إمتى بنبعت وإيه اللي بيتبعت».
 *
 * المهمة (`App\Jobs\SendOrderWhatsapp`) بتقرر المستلمين وبتبني النص وبتكتب
 * الجدول. المزوّد بياخد رسالة جاهزة ويرجّع نتيجة، وخلاص. الفصل ده هو اللي
 * بيخلّي التحوّل من اليدوي للتلقائي **تغيير إعداد** مش تغيير كود.
 *
 * 🔴 عقد ملزم على أي تطبيق: **ممنوع يرمي استثناء**. أي فشل — شبكة، إعداد
 * ناقص، رد غلط من المزوّد — بيرجع كـ`SendOutcome::failed()` أو
 * `notAttempted()` بسبب مكتوب. السبب: النداء بيحصل جوه مهمة الطابور اللي
 * أول شرط فيها إنها ماتكسرش حاجة، والاستثناء اللي بيطلع من هنا كان هيمنع
 * تسجيل الفشل نفسه في الجدول — يعني الفشل يبقى غير مرئي، وده أسوأ من الفشل.
 */
interface WhatsappProvider
{
    /**
     * المفتاح اللي بيتخزّن في عمود `order_notifications.provider`.
     * قيمة قصيرة ثابتة (العمود varchar(20)): `manual` أو `cloud_api`.
     *
     * بيتخزّن **حتى في الوضع اليدوي**، عشان لما الحساب يجهز ونحوّل، صفوف
     * الفترة اليدوية تفضل معروفة إنها اتسجّلت وهي يدوية.
     */
    public function key(): string;

    /**
     * يبعت رسالة واحدة لمستلم واحد.
     *
     * القالب اليدوي بيرجّع `awaitingHuman()` من غير أي شبكة — وده **نجاح**
     * بالنسبة له، مش فشل.
     */
    public function send(OutgoingMessage $message): SendOutcome;
}
