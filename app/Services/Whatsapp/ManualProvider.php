<?php

declare(strict_types=1);

namespace App\Services\Whatsapp;

/**
 * الوضع الافتراضي دلوقتي: **يدوي منظّم**.
 *
 * ═══ إيه اللي بيعمله ═══
 * لا حاجة. وده مش نقص في التطبيق — ده التطبيق.
 *
 * المهمة بتكون خلاص قررت المستلمين، طبّقت قواعد التخطّي، بنت النص، وكتبت
 * الصف بحالة `pending` **قبل** ما تنده هنا. المزوّد ده بيقول «تمام، سيبه
 * pending» وبس. الشغل الحقيقي اللي بيضيفه النظام في الوضع ده هو الجدول
 * نفسه: قبله مكانش فيه أثر إن رسالة اتبعتت ولا لأ — الموظف بيضغط زرار
 * واتساب في `store.html` والدنيا بتنتهي عند المتصفح. دلوقتي كل مستلم له
 * صف، بنصه، بحالته، ومنع التكرار بيتضمن من القاعدة مش من ذاكرة الموظف.
 *
 * ═══ ليه مش بيرجّع «تم» ═══
 * `sent` معناها **وصلت للمستلم**. الصف هنا لسه في انتظار بني آدم يضغط
 * زرار. لو رجّعنا `sent` كنا هنبقى كدّابين على أول تقرير «كام رسالة
 * اتبعتت» — والعمودين `sent_at`/`sent_by` كانوا هيتملوا بقيم متخيّلة.
 * الصف بيتحوّل لـ`sent` لما الموظف يأكّد من الشاشة (المسار ده مرحلة
 * تانية — الأساس هنا هو الجدول والمزوّد).
 */
final class ManualProvider implements WhatsappProvider
{
    public function key(): string
    {
        return 'manual';
    }

    public function send(OutgoingMessage $message): SendOutcome
    {
        /* مفيش شبكة، مفيش استثناء، مفيش تعديل على الصف.
           `attempts` بتفضل صفر لأن مافيش محاولة إرسال حصلت. */
        return SendOutcome::awaitingHuman();
    }
}
