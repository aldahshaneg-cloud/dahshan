<?php

declare(strict_types=1);

namespace App\Support;

/**
 * 💰 حسابات الفلوس المشتركة — تعريف واحد بدل نسخ متفرقة.
 */
final class Money
{
    /**
     * المبلغ اللي **الطيار بيحصّله كاش** من العميل.
     *
     * ═══ اللسعة اللي الدالة دي اتعملت عشانها ═══
     * العميل يقدر يدفع جزء (أو كل) سعر التوصيل من رصيد محفظته وقت إنشاء
     * الأوردر — والرصيد بيتخصم **فورًا** ساعتها. لكن تطبيق الطيار كان
     * بيعرض `totalDeliveryPrice` الخام على إنه «قيمة التحصيل»، وحساب
     * التسوية في الفرع كان بيطلب نفس الرقم الخام من الطيار.
     *
     * يعني أوردر بـ70 جنيه والعميل دفع 50 من محفظته:
     *   • المحفظة نزلت 50  ✅
     *   • الطيار شاف «قيمة التحصيل 70» وحصّل 70 كاش  ❌
     *   • الفرع طلب من الطيار 70  ❌
     *   ⟵ العميل دفع 120 على توصيلة بـ70. الزيادة = المخصوم بالظبط.
     *
     * حصلت فعلًا مرة واحدة على الإنتاج (أوردر HAL-260824-001، 30 جنيه).
     *
     * ═══ ليه هنا مش في تطبيق الطيار ═══
     * الإصلاح في السيرفر بيوصل **كل** الطيارين في نفس اللحظة، حتى اللي
     * مانزّلش نسخة جديدة. إصلاح في التطبيق كان هيسيب كل جهاز قديم بيغلط.
     *
     * `max(0, …)` لأن المخصوم مايزيدش عن السعر أصلًا، بس الحارس أرخص من
     * الثقة في بيانات مرحّلة.
     *
     * @param  array<string, mixed>  $order  صف الأوردر الخام من القاعدة
     */
    public static function netCollect(array $order): float
    {
        $total  = (float) ($order['total_delivery_price'] ?? 0);
        $wallet = (float) ($order['wallet_used'] ?? 0);

        return max(0.0, $total - $wallet);
    }

    /** نفس الحساب بس من كائن السلك (مفاتيح camelCase) */
    public static function netCollectWire(array $wire): float
    {
        $total  = (float) ($wire['totalDeliveryPrice'] ?? 0);
        $wallet = (float) ($wire['walletUsed'] ?? 0);

        return max(0.0, $total - $wallet);
    }

    /**
     * توزيع المخصوم من المحفظة على جزئين وقت **تفريق** الأوردر.
     *
     * ═══ اللسعة اللي الدالة دي اتعملت عشانها ═══
     * التفريق بيقسّم `total_delivery_price` على الأوردرين، بس كان بيسيب
     * `wallet_used` كله على الأصل والجزء المفصول بياخد صفر. ولأن التحصيل
     * بيتحسب `max(0, السعر − المحفظة)` لكل أوردر لوحده، الخصم بيتقصّ عند
     * صفر والباقي منه **بيتبخّر**:
     *
     *   أوردر 70 والعميل دفع 50 من محفظته ⟵ المفروض يتحصّل منه 20 كاش
     *   اتقسم 40 (جزء مفصول) + 30 (الأصل):
     *     • الجزء:  max(0, 40 − 0)  = 40   ❌
     *     • الأصل:  max(0, 30 − 50) = 0
     *     ⟵ المجموع 40 بدل 20. العميل دفع 20 زيادة — من فلوسه هو.
     *
     * التوزيع بالتناسب مع سعر كل جزء، والجزء التاني بيتحسب **بالطرح** مش
     * بضربة تانية — كده `أ + ب` بيساوي الأصل بالظبط ومفيش قرش بيتخلق أو
     * يضيع في التقريب.
     *
     * @param  float  $wallet  المخصوم من المحفظة على الأوردر الأصلي
     * @param  float  $partA   سعر توصيل الجزء المفصول
     * @param  float  $partB   سعر توصيل الباقي في الأصل
     * @return array{0: float, 1: float}  [نصيب المفصول, نصيب الأصل]
     */
    public static function splitWallet(float $wallet, float $partA, float $partB): array
    {
        if ($wallet <= 0.0) {
            return [0.0, 0.0];
        }
        $whole = $partA + $partB;
        /* أوردر بسعر صفر ومخصوم عليه محفظة = بيانات مرحّلة غلط. مافيش
           نسبة نقسم بيها، فبنسيب الخصم على الأصل زي ما هو بدل ما نقسمه
           بالتساوي — الأصل هو اللي فاضل بنفس الـid وسجلّه متربط بيه. */
        if ($whole <= 0.0) {
            return [0.0, round($wallet, 2)];
        }
        $a = round($wallet * $partA / $whole, 2);

        return [$a, round($wallet - $a, 2)];
    }
}
