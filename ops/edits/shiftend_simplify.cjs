/* تبسيط جسم الرفض: نستعمل الاختصار ApiException::forbidden زي باقي النظام،
 * ونشيل نداء pilotCtx.
 *
 * ليه بنشيل pilotCtx: الرفض واحد لأي طيار، وpilotCtx كانت هترمي «الطيار غير
 * موجود» (404) للحساب اللي مش مربوط بصف طيار — رسالة مضلّلة بتخفي السبب
 * الحقيقي. الوسيطة `role:pilot` على المسار كافية للتحقق من الدور، والاستعلام
 * الزيادة مالوش لازمة في مسار كل شغله يرفض.
 */
const fs = require('fs');
const p = 'app/Http/Controllers/Api/PilotAppController.php';
let s = fs.readFileSync(p, 'utf8');

const OLD = [
  '        /* 🔒 مقفول: الطيار مايقدرش ينهي ورديته. بننده `pilotCtx` الأول',
  '           عشان الحساب اللي مش مربوط بطيار ياخد 403 زي أي مسار طيار تاني',
  '           — الرد يفضل متسق مهما كان سبب الرفض. */',
  '        $this->pilotCtx($request);',
  '',
  '        throw new ApiException(',
  "            'إنهاء الوردية بقى من الفرع أو الإدارة — كلّم المشرف بتاعك',",
  '            403',
  '        );',
].join('\n');

const NEW = [
  '        /* 🔒 مقفول. مابنندهش `pilotCtx` هنا: الرفض واحد لأي طيار، وهي',
  '           كانت هترمي «الطيار غير موجود» (404) للحساب المش مربوط بصف',
  '           طيار — رسالة بتخفي السبب الحقيقي. الوسيطة `role:pilot` على',
  '           المسار كافية للتحقق من الدور. */',
  "        throw ApiException::forbidden('إنهاء الوردية بقى من الفرع أو الإدارة — كلّم المشرف بتاعك');",
].join('\n');

const n = s.split(OLD).length - 1;
if (n !== 1) { console.log(`🔴 اتلقت ${n} مرة — مالمستش حاجة`); process.exit(1); }
fs.writeFileSync(p, s.replace(OLD, NEW));
console.log('✅ اتبسّطت');
