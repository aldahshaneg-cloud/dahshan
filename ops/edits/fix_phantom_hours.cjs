/* 🔴 ساعات وهمية في تقفيلة الطيارين — الطيار اللي بيفتح أكتر من وردية.
 *
 * ═══ الباج ═══
 * `PilotAccountingController` بيجمّع مدة **كل وردية** صح (سطر ~258):
 *     $h = (ended_at − started_at) / 3600;
 *     $cell['hours'] += max(0, $h);
 * وبيسجّل كمان أول حضور وآخر انصراف في `in` و`out` — للعرض.
 *
 * وبعدين `dayRow` بترمي المجموع ده وتحسب من **المدى**:
 *     $hours = self::autoHours($in, $out, $perms) ?? $auto['hours'];
 * و`autoHours` بترجّع null **بس** لو وقت ناقص — يعني في الحالة العادية
 * المدى بيدهس المجموع دايمًا.
 *
 * ═══ الأثر بالأرقام (مقاس بالكود نفسه) ═══
 *     وردية ٩ص → ١ظ   = ٤ ساعات
 *     وردية ٦م → ١٠م   = ٤ ساعات
 *     الشغل الحقيقي    = ٨ ساعات
 *     اللي بيتعرض      = ١٣ ساعة   ← المدى ٩ص → ١٠م
 *     ٥ ساعات وهمية بتتدفع في المرتب.
 *
 * وكل ما الفجوة بين الورديتين تكبر، السرقة تكبر. طيار بيشتغل الصبح
 * ويرجع بالليل بياخد ساعات الراحة كأنها شغل.
 *
 * ═══ ليه المدى لسه محتاجينه ═══
 * لو المشرف كتب وقت حضور أو انصراف **بإيده**، فهو بيصف يوم مختلف عن
 * الورديات المسجّلة — ساعتها المدى بين وقتيه هو المقصود، ومجموع الورديات
 * مابقاش يمثّل اليوم. فالمدى بيفضل للحالة دي بس.
 *
 * ═══ الاستئذان ═══
 * `autoHours` بتطرح دقايق الاستئذان. مجموع الورديات **مابيطرحش** —
 * الكنترولر بيجمع المدد الخام. فالمسار الجديد بيطرحها بنفسه، وإلا الطيار
 * اللي أخد استئذان ساعة كان هياخدها مدفوعة.
 *
 * 🔒 الحارس: ops/test_pilot_hours.php
 */
const fs = require('fs');
const F = 'app/Wire/PilotAccountingWire.php';
let s = fs.readFileSync(F, 'utf8');
let bad = 0;

const one = (old, neu, label) => {
  const n = s.split(old).length - 1;
  if (n !== 1) { console.log('  🔴 ' + label + ': اتلقت ' + n + ' مرة'); bad++; return; }
  s = s.replace(old, neu);
  console.log('  ✓ ' + label);
};
const L = (...x) => x.join('\n');

/* ═══ ① الحساب ═══ */
one(
  L('        // الساعات: المكتوب بالإيد، وإلا المحسوب من الأوقات النهائية',
    '        $hoursOv = $ov(\'hours_override\');',
    '        $hours = $hoursOv !== null',
    '            ? round((float) $hoursOv, 2)',
    '            : (self::autoHours($in, $out, $perms) ?? round((float) ($auto[\'hours\'] ?? 0), 2));'),
  L('        /* الساعات — تلات مصادر بالترتيب:',
    '',
    '           ① المكتوب بالإيد (`hours_override`) — كلمة المشرف الأخيرة.',
    '',
    '           ② لو المشرف كتب وقت حضور أو انصراف بإيده، فهو بيصف يوم مختلف',
    '              عن الورديات المسجّلة — ساعتها المدى بين وقتيه هو المقصود.',
    '',
    '           ③ وإلا: **مجموع مدد الورديات** اللي الكنترولر حسبه.',
    '',
    '           🔴 التالتة دي كانت غلط: الكود كان بياخد المدى دايمًا',
    '           (`autoHours($in,$out)`)، و`$in`/`$out` هما **أول حضور وآخر',
    '           انصراف** في اليوم. طيار بوردية ٩ص→١ظ وتانية ٦م→١٠م شغل ٨',
    '           ساعات، والمدى بيقول ١٣ — خمس ساعات راحة بتتدفع كأنها شغل.',
    '           والمجموع الصح كان موجود في `$auto[\'hours\']` وبيترمي، لأن',
    '           `autoHours` مابترجّعش null غير لو وقت ناقص.',
    '',
    '           ⚠️ الاستئذان: `autoHours` بتطرحه، ومجموع الورديات لأ —',
    '           الكنترولر بيجمع المدد الخام. فالمسار التالت بيطرحه بنفسه،',
    '           وإلا الطيار اللي أخد استئذان ساعة بياخدها مدفوعة. */',
    '        $hoursOv = $ov(\'hours_override\');',
    '        $manualTime = $ov(\'time_in_override\') !== null || $ov(\'time_out_override\') !== null;',
    '',
    '        if ($hoursOv !== null) {',
    '            $hours = round((float) $hoursOv, 2);',
    '        } elseif ($manualTime || ($auto[\'hours\'] ?? null) === null) {',
    '            $hours = self::autoHours($in, $out, $perms) ?? 0.0;',
    '        } else {',
    '            $mins  = ((float) $auto[\'hours\']) * 60 - self::permMinutes($perms);',
    '            $hours = round(max(0, $mins) / 60, 2);',
    '        }'),
  '① مصدر الساعات');

if (bad) { console.log('\n🔴 ' + bad + ' مشكلة — مالمستش حاجة'); process.exit(1); }
fs.writeFileSync(F, s);
console.log('\n✅ الساعات بقت من مجموع الورديات');
