/* سعر التوصيل بقى مفتوح للمحل — بس مش أقل من سعر المنطقة.
 *
 * ═══ الطلب (صاحب النظام 2026-08-31) ═══
 * «اجعل سعر التوصيل مفتوح، ليس شرطًا أن يكون كما هو عند اختيار المنطقة،
 * بحيث يضع المحل السعر الذي يريده ولكن **ليس أقل** من السعر المرتبط
 * بالمنطقة».
 *
 * ═══ ليه السيرفر مش الواجهة بس ═══
 * `zonePrice` **بيتقبل من العميل من الأصل**:
 *     'zone_price' => isset($d['zonePrice']) && $d['zonePrice'] !== ''
 *                       ? (float) $d['zonePrice'] : (float) $zone['price']
 * يعني الرقم اللي بيتخزّن هو اللي الواجهة بعتته. فحد فتح الكونسول وكتب
 * سطر `fetch` يقدر يبعت سعر أقل — ودي مش نظرية: الرقم ده **فلوس**، بيتحسب
 * في مستحقات المحل وتقفيلة الفرع وعمولة الشركة.
 * ومش لازم يكون حد بيتعمّد: صفحة مفتوحة من امبارح وسعر المنطقة اتغيّر
 * بتبعت رقم قديم من غير ما حد ياخد باله.
 *
 * ═══ ليه رفض مش تقريب لأعلى ═══
 * التقريب الصامت بيخبّي عن المحل إن السعر اللي كتبه مااتاخدش، ويكتشف
 * الفرق في التقفيلة. الرفض برسالة فيها الحد الأدنى بيخلّيه يشوف السعر
 * الجديد ويقرر.
 *
 * ═══ ليه للمحل بس ═══
 * المسار مفتوح لـ branch و admin و callcenter و store و customer. الفرع
 * والإدارة ليهم سلطة تسعير (خصم لعميل، تسوية شكوى) — القيد عليهم بيكسر
 * شغل قايم. المحل هو اللي القاعدة دي اتطلبت له.
 *
 * 🔒 الحارس: ops/test_store_price_floor.php
 */
const fs = require('fs');
const F = 'app/Http/Controllers/Api/OrdersController.php';
let s = fs.readFileSync(F, 'utf8');
let bad = 0;

const one = (old, neu, label) => {
  const n = s.split(old).length - 1;
  if (n !== 1) { console.log('  🔴 ' + label + ': اتلقت ' + n + ' مرة'); bad++; return; }
  s = s.replace(old, neu);
  console.log('  ✓ ' + label);
};
const L = (...x) => x.join('\n');

one(
  L("                        'zone_name'       => (string) ($d['zoneName'] ?? $zone['area_name']),",
    "                        'zone_price'      => isset($d['zonePrice']) && $d['zonePrice'] !== ''",
    "                            ? (float) $d['zonePrice'] : (float) $zone['price'],"),
  L("                        'zone_name'       => (string) ($d['zoneName'] ?? $zone['area_name']),",
    "                        'zone_price'      => self::deliveryPrice($actor, $d, $zone, $no),"),
  'استدعاء الحد الأدنى');

/* الدالة نفسها — بنحطها جنب باقي المساعدات الساكنة */
one(
  "    /** المقابل لـ `trim((string)($b[k] ?? '')) ?: null` */",
  L('    /**',
    '     * سعر توصيل الطرد — المحل يقدر يزوّد، مايقدرش يقلّل.',
    '     *',
    '     * ═══ القاعدة (صاحب النظام 2026-08-31) ═══',
    '     * «سعر التوصيل مفتوح للمحل، بس ليس أقل من السعر المرتبط بالمنطقة».',
    '     *',
    '     * ═══ ليه هنا مش في الواجهة بس ═══',
    '     * الرقم ده بيتخزّن زي ما بيوصل، وبيتحسب في مستحقات المحل وتقفيلة',
    '     * الفرع وعمولة الشركة. قيد في الواجهة لوحده بيتخطّى بسطر `fetch`،',
    '     * وكمان صفحة مفتوحة من امبارح بتبعت سعر قديم من غير قصد.',
    '     *',
    '     * ═══ ليه للمحل بس ═══',
    '     * الفرع والإدارة ليهم سلطة تسعير (خصم لعميل، تسوية شكوى) — القيد',
    '     * عليهم بيكسر شغل قايم. والكول سنتر والعميل مابيبعتوش سعر مخصّص',
    '     * أصلًا، فالسطر ده مابيأثرش عليهم.',
    '     *',
    '     * ═══ ليه رفض مش تقريب لأعلى ═══',
    '     * التقريب الصامت بيخبّي عن المحل إن سعره مااتاخدش ويكتشفه في',
    '     * التقفيلة. الرسالة فيها الحد الأدنى عشان يشوف السعر الجديد.',
    '     */',
    '    private static function deliveryPrice(Actor $actor, array $d, array $zone, int $no): float',
    '    {',
    '        $floor = (float) $zone[\'price\'];',
    '        $sent  = isset($d[\'zonePrice\']) && $d[\'zonePrice\'] !== \'\' ? (float) $d[\'zonePrice\'] : null;',
    '',
    '        if ($sent === null) {',
    '            return $floor;',
    '        }',
    '        /* المقارنة بهامش صغير: الأسعار بتعدّي على float في الواجهة',
    '           وفي JSON، و`25.0 < 25.0` ممكن تطلع true من فروق التمثيل. */',
    '        if ($actor->role === \'store\' && $sent < $floor - 0.001) {',
    '            throw new ApiException(',
    '                \'سعر التوصيل للطرد رقم \' . $no . \' لا يقل عن \' . rtrim(rtrim(number_format($floor, 2, \'.\', \'\'), \'0\'), \'.\') . \' ج.م\'',
    '            );',
    '        }',
    '',
    '        return $sent;',
    '    }',
    '',
    "    /** المقابل لـ `trim((string)($b[k] ?? '')) ?: null` */"),
  'الدالة');

if (bad) { console.log('\n🔴 ' + bad + ' مشكلة — مالمستش حاجة'); process.exit(1); }
fs.writeFileSync(F, s);
console.log('\n✅ الحد الأدنى للسعر اتفرض على السيرفر');
