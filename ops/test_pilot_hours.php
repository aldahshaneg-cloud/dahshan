<?php
/**
 * ⏱ حارس: ساعات اليوم في تقفيلة الطيارين.
 *
 * ═══ الباج اللي اتصلّح (2026-09-01) ═══
 * `dayRow` كانت بتحسب الساعات من **المدى** بين أول حضور وآخر انصراف، بدل
 * **مجموع مدد الورديات** اللي الكنترولر حسبه صح.
 *
 *     وردية ٩ص → ١ظ  = ٤ ساعات
 *     وردية ٦م → ١٠م  = ٤ ساعات
 *     الشغل الحقيقي   = ٨ ساعات
 *     اللي كان بيتعرض = ١٣ ساعة  ← المدى ٩ص → ١٠م
 *
 * خمس ساعات راحة كانت بتتدفع كأنها شغل، وكل ما الفجوة بين الورديتين
 * تكبر السرقة تكبر.
 *
 * والمجموع الصح كان **موجود** في `$auto['hours']` وبيترمي — لأن
 * `autoHours` مابترجّعش null غير لو وقت ناقص، فالمدى كان بيدهسه دايمًا.
 *
 * ═══ الفحص بينفّذ مش بيقرا ═══
 * كل حالة بتنده `PilotAccountingWire::dayRow` **الحقيقية**. فحص نصّي كان
 * هيعدّي على أي إعادة صياغة بتدهس المجموع من جديد.
 *
 * التشغيل: php ops/test_pilot_hours.php
 */
require __DIR__ . '/../vendor/autoload.php';

use App\Wire\PilotAccountingWire as W;

$pass = 0;
$fail = 0;

function ok(string $what, bool $cond, string $got = ''): void
{
    global $pass, $fail;
    if ($cond) { $pass++; echo "  ✓ {$what}\n"; }
    else { $fail++; echo "  ✗ {$what}" . ($got !== '' ? "   ← {$got}" : '') . "\n"; }
}

function hours(array $auto, array $entry = [], array $perms = []): float
{
    return (float) W::dayRow(1, $auto, $entry, $perms)['hours'];
}

/* ورديتين متفرقتين — الحالة اللي كانت بتسرق */
$two = ['in' => '09:00', 'out' => '22:00', 'hours' => 8.0];
/* وردية واحدة — المدى والمجموع بيتساووا */
$one = ['in' => '09:00', 'out' => '17:00', 'hours' => 8.0];

echo "\n══ 1) 🔴 الباج نفسه ══\n";
$h = hours($two);
ok('ورديتين ٩→١ و ٦→١٠ = ٨ ساعات مش ١٣', abs($h - 8.0) < 0.01, (string) $h);
ok('   والفرق مش بيكبر مع الفجوة',
    abs(hours(['in' => '06:00', 'out' => '23:00', 'hours' => 8.0]) - 8.0) < 0.01,
    (string) hours(['in' => '06:00', 'out' => '23:00', 'hours' => 8.0]));

echo "\n══ 2) الحالات اللي مالهاش تتغيّر ══\n";
ok('وردية واحدة ٩→٥ = ٨', abs(hours($one) - 8.0) < 0.01, (string) hours($one));
ok('مفيش ورديات = صفر',
    abs(hours(['in' => null, 'out' => null, 'hours' => null])) < 0.01);
ok('وردية مفتوحة (مفيش انصراف) = صفر',
    abs(hours(['in' => '09:00', 'out' => null, 'hours' => 0.0])) < 0.01);

echo "\n══ 3) الاستئذان ══\n";
$perm1h = [['out' => '12:00', 'in' => '13:00']];
ok('ساعة استئذان بتتخصم من المجموع',
    abs(hours($two, [], $perm1h) - 7.0) < 0.01, (string) hours($two, [], $perm1h));
ok('واستئذانين بيتخصموا',
    abs(hours($two, [], [['out' => '12:00', 'in' => '13:00'], ['out' => '19:00', 'in' => '19:30']]) - 6.5) < 0.01,
    (string) hours($two, [], [['out' => '12:00', 'in' => '13:00'], ['out' => '19:00', 'in' => '19:30']]));
ok('🔴 واستئذان أطول من الشغل مابيدّيش سالب',
    hours(['in' => '09:00', 'out' => '10:00', 'hours' => 1.0], [], [['out' => '09:00', 'in' => '15:00']]) >= 0);

echo "\n══ 4) تدخّل المشرف ══\n";
ok('الساعات المكتوبة بالإيد بتكسب كل حاجة',
    abs(hours($two, ['hours_override' => '6']) - 6.0) < 0.01);
ok('وصفر مكتوب بالإيد بيتحفظ — مش بيترجع للتلقائي',
    abs(hours($two, ['hours_override' => '0'])) < 0.01,
    (string) hours($two, ['hours_override' => '0']));
/* لو المشرف كتب وقت بإيده فهو بيصف يوم مختلف عن الورديات المسجّلة،
   ساعتها المدى بين وقتيه هو المقصود ومجموع الورديات مابقاش يمثّل اليوم */
ok('وقت انصراف مكتوب بالإيد → المدى ٩→٦ = ٩ ساعات',
    abs(hours($two, ['time_out_override' => '18:00']) - 9.0) < 0.01,
    (string) hours($two, ['time_out_override' => '18:00']));
ok('ووقت حضور مكتوب بالإيد كمان',
    abs(hours($two, ['time_in_override' => '10:00']) - 12.0) < 0.01,
    (string) hours($two, ['time_in_override' => '10:00']));
ok('والوقت اليدوي بيتخصم منه الاستئذان برضه',
    abs(hours($two, ['time_out_override' => '18:00'], $perm1h) - 8.0) < 0.01,
    (string) hours($two, ['time_out_override' => '18:00'], $perm1h));

echo "\n══ 5) المصدر — الحارس ضد الرجوع ══\n";
$src = file_get_contents(__DIR__ . '/../app/Wire/PilotAccountingWire.php');
/* بنشيل التعليقات قبل الفحص النصّي — التعليق الجديد بيشرح الباج وبيذكر
   `autoHours($in, $out, $perms)`، والفحص كان هيمسك شرحه هو. */
$code = preg_replace('#/\*[\s\S]*?\*/|//[^\n]*#', '', $src);
/* الفحص على **شكل الباج** بالظبط: المدى وبعده `??` وبعده المجموع.
   الأول كتبته `autoHours(...) ??` وبس فمسك الفرع المشروع كمان —
   `autoHours(...) ?? 0.0` في مسار الوقت اليدوي، وده صح ومالوش علاقة. */
ok('🔴 مافيش رجوع لـ«المدى ?? المجموع»',
    ! preg_match('/self::autoHours\([^)]*\)\s*\?\?[^;]*\$auto\[\x27hours\x27\]/', $code),
    'المدى رجع يدهس المجموع');
ok('المجموع بيتستعمل لما مفيش تدخّل يدوي',
    (bool) preg_match('/\$auto\[\x27hours\x27\]\)\s*\*\s*60\s*-\s*self::permMinutes/', $code));
ok('والمدى لسه للوقت المكتوب بالإيد',
    (bool) preg_match('/\$manualTime[\s\S]{0,120}self::autoHours/', $code));

echo "\n" . str_repeat('─', 50) . "\n";
echo $fail === 0
    ? "✅ عدّى {$pass} فحص — الساعات من مجموع الورديات\n\n"
    : "🔴 وقع {$fail} من " . ($pass + $fail) . "\n\n";
exit($fail === 0 ? 0 : 1);
