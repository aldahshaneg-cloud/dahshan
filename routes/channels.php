/**
 * قناة الفرع — `private-branch.{branchId}`
 *
 * اللي بيسمع عليها: لوحة الفرع، والكول سنتر، والأدمن.
 *
 * التفويض مطابق لنطاق الأدوار في `OrdersController::index()`:
 *   • admin / callcenter → أي فرع (بيشوفوا الشركة كلها أصلًا)
 *   • branch            → فرعه هو بس، مقارنة بالرقم مش بالنص
 *   • أي دور تاني (pilot / store / customer / accountant / hr) → مرفوض
 *
 * الطيار والمحل والعميل نطاقهم **مش الفرع** (`pilot_id` / `added_by` /
 * `customer_id`)، فقناة الفرع كانت هتوريهم أوردرات مش بتاعتهم. قنواتهم
 * هتتعرّف لوحدها لما توصل مرحلة تحويل تطبيق الطيار ولوحة المحل.
 */
Broadcast::channel('branch.{branchId}', function (?Actor $actor, string $branchId): bool {
    if (! $actor instanceof Actor) {
        return false;
    }

    /* اسم القناة نص جاي من العميل — «5abc» أو «0» أو «-3» أو فاضي كلها
       ممكنة. `filter_var` أصرم من `(int)`: بترفض أي كتابة مش قانونية بما
       فيها الصفر البادئ («07»). ده مقصود — السيرفر نفسه بيولّد الاسم من
       `(int) $branchId` فبيطلع دايمًا شكل واحد، والصرامة دي بتمنع إن
       الفرع الواحد يتقسم على قناتين («branch.7» و«branch.07») ونص
       المشتركين مايوصلهمش الحدث. */
    $wanted = dahshan_channel_id($branchId);
    if ($wanted === null) {
        return false;
    }

    /* مشرف الطيارين اتضاف 2026-08-22 مع حدث `pilot.request.changed`:
       طلبات الإذن والورديات هي شغله الأساسي، ولوحته (pilots.html) محتاجة
       تسمع القناة دي عشان الطلب يظهر فورًا بدل مستطلع الدقيقة. القناة
       بتشيل كمان إشعارات `order.changed` (id ورقم وحالة — بلا أي فلوس)،
       ودي جوه نطاقه التشغيلي أصلًا (بيشوف البورد من role:pilot_supervisor). */
    if ($actor->hasRole('admin', 'callcenter', 'pilot_supervisor')) {
        return true;
    }

    if ($actor->role === 'branch') {
        // branchId ممكن يكون null لحساب فرع ناقص بياناته — null ≠ أي فرع
        return $actor->branchId !== null && $actor->branchId === $wanted;
    }

    return false;
});

/**
 * قناة الطيار — `private-pilot.{pilotId}`
 *
 * اللي بيسمع عليها: تطبيق الطيار (Flutter) وبس. الأوردر اللي عليه طيار
 * بيتبثّ على قناتين: قناة فرعه **و** القناة دي (`OrderChanged::broadcastOn`).
 *
 * التفويض مطابق لقاعدة `PilotAppController::pilotCtx()` بالحرف:
 * **الطيار بيتحدّد من الحساب مش من باراميتر**. الرقم اللي جوه اسم القناة
 * مش هوية — ده **طلب** جاي من العميل؛ الهوية الحقيقية بتتقرا من
 * `users.pilot_id` بتاع الحساب المصادَق، والقناة بتتفتح بس لما الاتنين
 * يتطابقوا. أي قراءة للباراميتر كمصدر للهوية هنا = أي طيار يسمع أي طيار.
 *
 * ═══ 🔴 القرار: الأدمن والكول سنتر **مرفوضين** هنا ═══
 * عن قصد، وعلى عكس قناة الفرع فوق. الأسباب بالترتيب:
 *
 * ١. **مابيفيدش حد.** كل حدث بيتبعت على `pilot.{id}` بيتبعت في نفس اللحظة
 *    على `branch.{branchId}` بتاع نفس الأوردر — الاتنين راجعين من نفس نداء
 *    `broadcastOn()`. والأدمن/الكول سنتر مصرّح لهم على **كل** قناة فرع
 *    أصلًا. يعني السماح هنا بيديهم **صفر** حدث جديد؛ مكسب معدوم بالظبط.
 *
 * ٢. **وبيوسّع سطح التعرّض.** بيفتح فضاء أسماء مفتوح (أي رقم صحيح) لكل
 *    حساب أدمن أو كول سنتر — وحسابات الكول سنتر أكتر بكتير من الأدمن
 *    وبتتوزّع على موظفين بيروحوا ويجوا. توكن كول سنتر مسروق ساعتها بيترقّى
 *    من «يقرا أوردرات فرع» لـ«يتتبّع طيار بعينه لحظة بلحظة» — نفس البيانات
 *    بس مركّزة على شخص، وده تتبّع مش تشغيل.
 *
 * ٣. **عدم التماثل مع قناة الفرع مقصود مش سهو.** هناك السماح للأدمن بيديه
 *    حاجة مالوش طريق تاني ليها: الأحداث بتتوزّع على الفروع وخلاص، فمن غير
 *    قناة الفرع مايشوفش حاجة. هنا العكس — القناة دي مجرد نسخة مركّزة من
 *    حاجة شايفها كلها بالفعل.
 *
 * مفيش سطر رفض صريح للأدمن تحت: القاعدة نفسها بترفضه لأن حساب الأدمن مش
 * مربوط بطيار (`users.pilot_id` = NULL). ولو حد ربط حساب أدمن بطيار يومًا،
 * هياخد قناته زي ما هياخد **مسارات تطبيق الطيار كلها** من `pilotCtx()` —
 * الاتساق ده مقصود: قاعدة واحدة، مكانين.
 *
 * ولو احتاجنا يوم «الأدمن يتفرّج على طيار بعينه»، الطريق قناة تانية باسمها
 * وتفويضها (زي `company` المقترحة في docs/REALTIME.md §6) — مش توسعة الدالة
 * دي، عشان التوسعة تبان في المراجعة بدل ما تعدّي كسطر شرط زيادة.
 */
Broadcast::channel('pilot.{pilotId}', function (?Actor $actor, string $pilotId): bool {
    if (! $actor instanceof Actor) {
        return false;
    }

    /* نفس صرامة قناة الفرع بالحرف ونفس السبب: `filter_var` بترفض كل كتابة
       مش قانونية بما فيها الصفر البادئ («07»)، عشان الطيار الواحد مايتقسمش
       على قناتين («pilot.7» و«pilot.07») ونص أجهزته مايوصلهاش الحدث.
       السيرفر بيولّد الاسم من `(int) $pilotId` فبيطلع دايمًا شكل واحد. */
    $wanted = dahshan_channel_id($pilotId);
    if ($wanted === null) {
        return false;
    }

    /* عميل التطبيق مالوش `user_id` أصلًا — `Actor::customer()` بتحطها null
       بالقصد. من غير الفحص ده الاستعلام كان هيروح للقاعدة بـ`WHERE id = NULL`
       ويرجّع صفر صفوف: نفس النتيجة بالظبط، بس بطلب قاعدة زيادة على كل
       محاولة اشتراك — والمحاولات دي مش لازم تكون من حساب سليم أصلًا. */
    if ($actor->userId === null) {
        return false;
    }

    /* 🔒 الهوية من الحساب مش من الباراميتر — نفس ربط `pilotCtx()` بالحرف:
       `users.pilot_id → pilots.id`. الحساب المش مربوط بطيار بيرجّع NULL
       وبيترفض، وده المقابل المباشر لـ403 «الحساب مش مربوط بطيار».

       `pilotCtx()` بتعمل `JOIN pilots` كمان لأنها محتاجة صف الطيار نفسه
       (الاسم والفرع)؛ هنا محتاجين الرقم بس، وفيه مفتاح أجنبي
       `fk_users_pilot_id` على العمود فصف الطيار موجود بالضرورة — الـJOIN
       مايقدرش يغيّر القرار، فهو طلب زيادة على مسار التفويض من غير مقابل. */
    $mine = DB::table('users')->where('id', $actor->userId)->value('pilot_id');

    return $mine !== null && (int) $mine === $wanted;
});
