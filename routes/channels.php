/**
 * الشكل القانوني الوحيد لرقم في اسم قناة.
 *
 * 🔴 ليه مش filter_var(FILTER_VALIDATE_INT):
 * الأخيرة بتقبل الفراغ المحيط وعلامة الزائد — "5 " و " 5" و "+5" كلهم
 * بيبقوا 5. ونمط لارافل {pilotId} بيتحوّل لـ ([^.]+) اللي بيلقّط المسافة
 * عادي. النتيجة: "private-pilot.5" و "private-pilot.+5" اسمين مختلفين عند
 * Reverb بنفس التفويض بالظبط — نص الأجهزة بتشترك في قناة والنص التاني في
 * قناة تانية، والحدث بيوصل لنص المشتركين بس.
 *
 * كان موجود في قناة الفرع من الأصل، واتكشف وقت بناء قناة الطيار (2026-08-20).
 * القاعدة هنا مشتركة عن قصد: أي تضييق بيتطبّق على القناتين مرة واحدة،
 * و tests/realtime_channels.php فيه قسم بيقارن صرامة الدالتين فبيمسك أي افتراق.
 */
/* 🔴 الحارس مش زيادة — `bootstrap/app.php` بيحمّل الملف ده بـ`require`
   (مش `require_once`) جوه `booted()`، و`artisan route:cache` بيبني **نسخة
   تانية من التطبيق في نفس العملية** فالملف بيتحمّل مرتين. من غير الحارس:
   «Cannot redeclare dahshan_channel_id» و**أمر النشر كله بيقع**.
   (اتكشف في مراجعة 2026-08-20 بعد ما الدالة اتضافت بساعة.) */
if (! function_exists('dahshan_channel_id')) {
    function dahshan_channel_id(string $raw): ?int
    {
        return preg_match('/^[1-9]\d*$/', $raw) === 1 ? (int) $raw : null;
    }
}

